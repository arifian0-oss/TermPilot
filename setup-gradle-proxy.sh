#!/bin/bash
# Regenerates Gradle proxy configuration from the LIVE proxy env vars.
# Proxy credentials rotate, so run this before every build session.
# Never hardcode credentials here or in gradle.properties.
set -euo pipefail

PROXY_URL="${https_proxy:-${HTTPS_PROXY:-${http_proxy:-${HTTP_PROXY:-}}}}"
if [ -z "$PROXY_URL" ]; then
  echo "No proxy env var set; skipping proxy config."
  exit 0
fi

# Parse proxy URL safely with python (handles user:pass@host:port).
read -r HOST PORT USER PASS NOPROXY <<< "$(
python3 - "$PROXY_URL" "${no_proxy:-}" <<'EOF'
import sys, urllib.parse
u = urllib.parse.urlparse(sys.argv[1])
host = u.hostname or ""
port = u.port or 3128
user = urllib.parse.unquote(u.username or "")
pw = urllib.parse.unquote(u.password or "")
# Java nonProxyHosts uses | separators, no brackets/ports
noproxy = "|".join(h.strip().strip("[]").split(":")[0] for h in sys.argv[2].split(",") if h.strip()) if len(sys.argv) > 2 else ""
print(f"{host} {port} {user} {pw} {noproxy}")
EOF
)"

{
  echo "# Generated by setup-gradle-proxy.sh from live env on $(date -u +%FT%TZ). Credentials rotate; regenerate, do not hand-edit."
  echo "systemProp.http.proxyHost=$HOST"
  echo "systemProp.http.proxyPort=$PORT"
  echo "systemProp.https.proxyHost=$HOST"
  echo "systemProp.https.proxyPort=$PORT"
  [ -n "$USER" ] && echo "systemProp.http.proxyUser=$USER"
  [ -n "$PASS" ] && echo "systemProp.http.proxyPassword=$PASS"
  [ -n "$USER" ] && echo "systemProp.https.proxyUser=$USER"
  [ -n "$PASS" ] && echo "systemProp.https.proxyPassword=$PASS"
  [ -n "$NOPROXY" ] && echo "systemProp.http.nonProxyHosts=$NOPROXY"
  [ -n "$NOPROXY" ] && echo "systemProp.https.nonProxyHosts=$NOPROXY"
  # Sandbox quirk: Gradle client connects to the daemon via IPv4-mapped IPv6
  # (::ffff:127.0.0.1) which the daemon's IPv4-only listener rejects.
  # Forcing IPv4 fixes "Could not receive a message from the daemon".
  echo "systemProp.java.net.preferIPv4Stack=true"
} > /tmp/gradle-props.tmp
chmod 600 /tmp/gradle-props.tmp

# Gradle resolves user.home to /root here (observed), but HOME=/home/hatch.
# Write to both locations to be safe.
mkdir -p /root/.gradle /home/hatch/.gradle
cp /tmp/gradle-props.tmp /root/.gradle/gradle.properties
cp /tmp/gradle-props.tmp /home/hatch/.gradle/gradle.properties
chmod 600 /root/.gradle/gradle.properties /home/hatch/.gradle/gradle.properties
rm -f /tmp/gradle-props.tmp
echo "Wrote proxy config for $HOST:$PORT (auth: $([ -n "$USER" ] && echo yes || echo no))"
